def set_run_font(run, size=11, bold=False, color=None):
    run.font.name = "Calibri"
    run._element.rPr.rFonts.set(qn("w:eastAsia"), "宋体")
    run.font.size = Pt(size)
    run.bold = bold
    if color:
        run.font.color.rgb = RGBColor.from_string(color)


def set_para(paragraph, before=0, after=6, line=1.15, align=None):
    fmt = paragraph.paragraph_format
    fmt.space_before = Pt(before)
    fmt.space_after = Pt(after)
    fmt.line_spacing = line
    if align is not None:
        paragraph.alignment = align


def add_p(doc, text="", size=11, bold=False, after=6, before=0, align=None, color=None):
    p = doc.add_paragraph()
    set_para(p, before=before, after=after, align=align)
    r = p.add_run(text)
    set_run_font(r, size=size, bold=bold, color=color)
    return p


def add_heading(doc, text, level=1):
    p = doc.add_paragraph()
    before = 16 if level == 1 else 10
    after = 8 if level == 1 else 5
    size = 15 if level == 1 else 12
    color = "1F4D78" if level == 1 else "2E74B5"
    set_para(p, before=before, after=after)
    r = p.add_run(text)
    set_run_font(r, size=size, bold=True, color=color)
    return p


def add_clause(doc, number, title, paragraphs):
    add_heading(doc, f"第{number}条 {title}", 1)
    for text in paragraphs:
        add_p(doc, text)


def set_cell_text(cell, text, bold=False, width=None):
    cell.vertical_alignment = WD_CELL_VERTICAL_ALIGNMENT.CENTER
    p = cell.paragraphs[0]
    p.alignment = WD_ALIGN_PARAGRAPH.LEFT
    set_para(p, after=0, line=1.1)
    r = p.add_run(text)
    set_run_font(r, size=10.5, bold=bold)
    if width:
        cell.width = width


def shade_cell(cell, fill):
    tc_pr = cell._tc.get_or_add_tcPr()
    shd = OxmlElement("w:shd")
    shd.set(qn("w:fill"), fill)
    tc_pr.append(shd)


def add_kv_table(doc, rows):
    table = doc.add_table(rows=0, cols=2)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.style = "Table Grid"
    for label, value in rows:
        cells = table.add_row().cells
        set_cell_text(cells[0], label, bold=True)
        set_cell_text(cells[1], value)
        shade_cell(cells[0], "F2F4F7")
    add_p(doc, "", after=2)
    return table


def add_check_table(doc, rows):
    table = doc.add_table(rows=1, cols=3)
    table.alignment = WD_TABLE_ALIGNMENT.CENTER
    table.style = "Table Grid"
    headers = ["验收项", "通过标准", "备注"]
    for idx, header in enumerate(headers):
        set_cell_text(table.rows[0].cells[idx], header, bold=True)
        shade_cell(table.rows[0].cells[idx], "E8EEF5")
    for item, standard, note in rows:
        cells = table.add_row().cells
        set_cell_text(cells[0], item)
        set_cell_text(cells[1], standard)
        set_cell_text(cells[2], note)
    add_p(doc, "", after=2)
    return table


